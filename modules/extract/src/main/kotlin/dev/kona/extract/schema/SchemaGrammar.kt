package dev.kona.extract.schema

import dev.kona.extract.Grammar

/**
 * Turns a [Blueprint] into DDL statements. The base class emits standard SQL that both H2 and
 * PostgreSQL accept; subclasses override only the types or statements that differ.
 */
open class SchemaGrammar @JvmOverloads constructor(val identifiers: Grammar = Grammar.ANSI) {
    open fun wrap(identifier: String): String = identifiers.wrap(identifier)

    open fun type(column: ColumnDefinition): String = when (column.type) {
        ColumnType.ID -> "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        ColumnType.STRING -> "VARCHAR(${column.length})"
        ColumnType.TEXT -> "TEXT"
        ColumnType.INTEGER -> "INTEGER"
        ColumnType.BIG_INTEGER -> "BIGINT"
        ColumnType.BOOLEAN -> "BOOLEAN"
        ColumnType.TIMESTAMP -> "TIMESTAMP"
    }

    open fun column(column: ColumnDefinition): String {
        val sql = StringBuilder(wrap(column.name)).append(' ').append(type(column))
        if (column.type != ColumnType.ID) {
            sql.append(if (column.isNullable) " NULL" else " NOT NULL")
        }
        if (column.useCurrent) {
            sql.append(" DEFAULT CURRENT_TIMESTAMP")
        } else if (column.hasDefault) {
            sql.append(" DEFAULT ").append(literal(column.defaultValue))
        }
        return sql.toString()
    }

    open fun literal(value: Any?): String = when (value) {
        null -> "NULL"
        is Boolean -> if (value) "TRUE" else "FALSE"
        is Number -> value.toString()
        else -> "'" + value.toString().replace("'", "''") + "'"
    }

    open fun foreignKey(key: ForeignKeyDefinition): String {
        val sql = StringBuilder("CONSTRAINT ").append(wrap(key.name))
            .append(" FOREIGN KEY (").append(wrap(key.column)).append(")")
            .append(" REFERENCES ").append(wrap(key.onTable))
            .append(" (").append(wrap(key.referencesColumn)).append(")")
        key.onDeleteAction?.let { sql.append(" ON DELETE ").append(it) }
        key.onUpdateAction?.let { sql.append(" ON UPDATE ").append(it) }
        return sql.toString()
    }

    open fun createIndex(table: String, index: IndexDefinition): String {
        val kind = if (index.unique) "CREATE UNIQUE INDEX " else "CREATE INDEX "
        return kind + wrap(index.name) + " ON " + wrap(table) +
            " (" + index.columns.joinToString(", ") { wrap(it) } + ")"
    }

    open fun compileCreate(blueprint: Blueprint): List<String> {
        require(blueprint.columns.isNotEmpty()) { "Table [${blueprint.table}] needs at least one column" }
        val parts = blueprint.columns.map { column(it) } + blueprint.foreignKeys.map { foreignKey(it) }
        val create = "CREATE TABLE " + wrap(blueprint.table) + " (" + parts.joinToString(", ") + ")"
        return listOf(create) + blueprint.indexes.map { createIndex(blueprint.table, it) }
    }

    open fun compileAlter(blueprint: Blueprint): List<String> {
        val table = wrap(blueprint.table)
        return blueprint.dropIndexes.map { compileDropIndex(blueprint.table, it) } +
            blueprint.dropColumns.map { "ALTER TABLE $table DROP COLUMN ${wrap(it)}" } +
            blueprint.columns.map { "ALTER TABLE $table ADD COLUMN ${column(it)}" } +
            blueprint.foreignKeys.map { "ALTER TABLE $table ADD ${foreignKey(it)}" } +
            blueprint.indexes.map { createIndex(blueprint.table, it) }
    }

    open fun compileDropIndex(table: String, index: String): String = "DROP INDEX " + wrap(index)

    open fun compileDrop(table: String): String = "DROP TABLE " + wrap(table)

    open fun compileDropIfExists(table: String): String = "DROP TABLE IF EXISTS " + wrap(table)

    open fun compileRename(from: String, to: String): String = "ALTER TABLE " + wrap(from) + " RENAME TO " + wrap(to)

    companion object {
        @JvmField
        val STANDARD: SchemaGrammar = SchemaGrammar()

        @JvmField
        val H2: SchemaGrammar = H2SchemaGrammar()

        @JvmField
        val POSTGRES: SchemaGrammar = STANDARD

        /**
         * Picks a grammar from a JDBC `DatabaseMetaData.getDatabaseProductName()` value; [identifiers]
         * should match the connection's query [Grammar] so DDL and queries name tables the same way.
         */
        @JvmStatic
        @JvmOverloads
        fun forProduct(product: String, identifiers: Grammar = Grammar.ANSI): SchemaGrammar {
            val h2 = product.equals("H2", ignoreCase = true)
            if (identifiers === Grammar.ANSI) {
                return if (h2) H2 else STANDARD
            }
            return if (h2) H2SchemaGrammar(identifiers) else SchemaGrammar(identifiers)
        }
    }
}

/** H2 has no unbounded `TEXT` that reads back as a plain string, so text maps to `CHARACTER VARYING`. */
class H2SchemaGrammar @JvmOverloads constructor(identifiers: Grammar = Grammar.ANSI) : SchemaGrammar(identifiers) {
    override fun type(column: ColumnDefinition): String =
        if (column.type == ColumnType.TEXT) "CHARACTER VARYING" else super.type(column)
}
