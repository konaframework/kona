package dev.kona.support.str

import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertFalse
import org.junit.jupiter.api.Assertions.assertNotEquals
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test

class StrTest {
    @Test
    fun staticHelpers() {
        assertEquals("", Str.lower(""))
        assertEquals("hello", Str.lower("HeLLo"))
        assertEquals("HELLO", Str.upper("HeLLo"))
        assertEquals("Hello World", Str.title("hello   world"))
        assertEquals("", Str.title(""))
        assertEquals("", Str.camel(""))
        assertEquals("helloWorld", Str.camel("hello_world"))
        assertEquals("HelloWorld", Str.studly("hello-world"))
        assertEquals("", Str.studly("___"))
        assertEquals("hello_world", Str.snake("HelloWorld"))
        assertEquals("hello_world", Str.snake("Hello__World"))
        assertEquals("hello-world", Str.kebab("HelloWorld"))
        assertEquals("hello-world", Str.slug("Hello World!!!"))
        assertEquals("hello", Str.slug("hello", "*").trim('*'))
        assertEquals("hello-world", Str.slug("Hello World", "-"))
        assertEquals("hello-world", Str.slug("Hello World", ""))
        assertEquals("abc", Str.limit("abc", 10))
        assertEquals("ab...", Str.limit("abcdef", 2))
        assertEquals("...", Str.limit("abcdef", 0))
        assertEquals("--", Str.limit("abcdef", 0, "--"))
        assertTrue(Str.contains("Hello", "ell"))
        assertTrue(Str.contains("Hello", "ELL", ignoreCase = true))
        assertFalse(Str.contains("Hello", "xyz"))
        assertTrue(Str.startsWith("hello", "he"))
        assertTrue(Str.endsWith("hello", "lo"))
        assertEquals("hel", Str.before("hello", "lo"))
        assertEquals("hello", Str.before("hello", "zz"))
        assertEquals("lo", Str.after("hello", "hel"))
        assertEquals("hello", Str.after("hello", "zz"))
        assertEquals("heix", Str.replace("llo", "ix", "hello"))
        assertEquals(8, Str.random(8).length)
        assertEquals(0, Str.random(0).length)
        assertEquals(16, Str.random().length)
        assertTrue(Str.uuid().contains("-"))
        assertTrue(Str.isBlank(null))
        assertTrue(Str.isBlank("  "))
        assertFalse(Str.isBlank("x"))
        assertTrue(Str.isNotBlank("x"))
        assertFalse(Str.isNotBlank(null))
    }

    @Test
    fun stringableChain() {
        assertEquals("", Str.of(null).lower().toStringValue())
        val s = Str.of("Hello_World")
            .lower()
            .upper()
            .title()
            .camel()
            .studly()
            .snake()
            .kebab()
            .slug()
            .limit(20)
            .append("!")
            .prepend(">")
            .finish("!")
            .start(">")
        assertTrue(s.toString().startsWith(">"))
        assertEquals(s.toStringValue(), s.toString())
        assertEquals(Stringable("a"), Stringable("a"))
        assertEquals(Stringable("a").hashCode(), Stringable("a").hashCode())
        assertNotEquals(Stringable("a"), Stringable("b"))
        assertNotEquals(Stringable("a"), "a")
        assertEquals("path/", Str.of("path").finish("/").toString())
        assertEquals("path/", Str.of("path/").finish("/").toString())
        assertEquals("/path", Str.of("path").start("/").toString())
        assertEquals("/path", Str.of("/path").start("/").toString())
        assertEquals("Hello World", Str.of("hello world").title().toString())
    }

    @Test
    fun deepenSegmentsMaskPad() {
        assertEquals("a/b", Str.beforeLast("a/b/c", "/"))
        assertEquals("a/b/c", Str.beforeLast("a/b/c", "|"))
        assertEquals("c", Str.afterLast("a/b/c", "/"))
        assertEquals("a/b/c", Str.afterLast("a/b/c", "|"))
        assertEquals("mid", Str.between("[mid]", "[", "]"))
        assertEquals("Hello World", Str.headline("hello_world"))
        assertEquals("ab***f", Str.mask("abcdef", "*", 2, 3))
        assertEquals("abcdef", Str.mask("abcdef", "*", 10, 2))
        assertEquals("abcdef", Str.mask("abcdef", "", 0, 2))
        assertEquals("", Str.mask("", "*", 0, 1))
        assertEquals("******", Str.mask("abcdef", "*"))
        assertEquals(3, Str.length("abc"))
        assertEquals("bcd", Str.substr("abcd", 1, 3))
        assertEquals("cd", Str.substr("abcd", -2))
        assertEquals("abcd", Str.substr("abcd", 0))
        assertEquals("", Str.substr("abcd", 0, 0))
        assertEquals("aaa", Str.repeat("a", 3))
        assertEquals("", Str.repeat("a", 0))
        assertEquals("00ab", Str.padLeft("ab", 4, "0"))
        assertEquals("ab", Str.padLeft("ab", 2, "0"))
        assertEquals("ab", Str.padLeft("ab", 4, ""))
        assertEquals("ab00", Str.padRight("ab", 4, "0"))
        assertEquals("ab", Str.padRight("ab", 1, "0"))
        assertEquals("ab", Str.padRight("ab", 4, ""))
        assertEquals("  ab", Str.padLeft("ab", 4))
        assertEquals("ab  ", Str.padRight("ab", 4))
    }
}
