package org.konaframework.grind

import java.nio.file.Files
import java.nio.file.LinkOption
import java.nio.file.Path
import java.nio.file.StandardCopyOption
import java.nio.file.attribute.PosixFilePermissions

/**
 * Files and text for `./grind deploy:systemd`: a production tree plus a systemd unit,
 * EnvironmentFile, and `install.sh`.
 */
internal object SystemdPackager {
    const val DEFAULT_USER = "kona"
    const val DEFAULT_HOST = "127.0.0.1"
    const val DEFAULT_PORT = 4000
    const val DEFAULT_JAVA_OPTS = "-XX:+UseG1GC -XX:MaxRAMPercentage=75.0"

    private val ROOT_PROJECT_NAME = Regex("""rootProject\.name\s*=\s*["']([^"']+)["']""")

    private val PRODUCTION_OVERLAY =
        linkedMapOf(
            "APP_ENV" to "production",
            "APP_DEBUG" to "false",
            "LOG_TO_FILE" to "true",
        )

    private val ENV_KEY_ORDER =
        listOf(
            "APP_NAME",
            "APP_ENV",
            "APP_DEBUG",
            "APP_URL",
            "APP_KEY",
            "HOST",
            "PORT",
            "LOG_LEVEL",
            "LOG_TO_FILE",
            "DB_CONNECTION",
            "DB_URL",
            "DB_USERNAME",
            "DB_PASSWORD",
            "DB_DRIVER",
            "DB_POOL_SIZE",
            "SESSION_DRIVER",
            "CACHE_STORE",
            "QUEUE_CONNECTION",
            "REDIS_CLIENT",
            "REDIS_HOST",
            "REDIS_PORT",
            "REDIS_PASSWORD",
            "REDIS_URL",
            "JAVA_OPTS",
        )

    fun parseRootProjectName(text: String): String? {
        val match = ROOT_PROJECT_NAME.find(text) ?: return null
        val name = match.groupValues[1].trim()
        if (name.isEmpty()) {
            return null
        }
        return name
    }

    fun readAppName(root: Path): String {
        for (file in listOf("settings.gradle.kts", "settings.gradle")) {
            val path = root.resolve(file)
            if (Files.isRegularFile(path)) {
                parseRootProjectName(Files.readString(path))?.let { return it }
            }
        }
        return root.fileName.toString()
    }

    fun sanitizeUnitName(raw: String): String {
        val s = raw.trim().lowercase().replace(Regex("[^a-z0-9._-]+"), "-").trim { it == '-' || it == '.' }
        if (s.isEmpty()) {
            throw GrindException("Invalid application name: '$raw'")
        }
        return s
    }

    fun parsePort(raw: String): Int {
        val n = raw.toIntOrNull() ?: throw GrindException("Invalid PORT value: $raw")
        if (n !in 1..65535) {
            throw GrindException("Invalid PORT value: $raw")
        }
        return n
    }

    fun overlayEnv(
        source: Map<String, String>,
        appName: String,
        host: String,
        port: Int,
        url: String,
        javaOpts: String,
    ): LinkedHashMap<String, String> {
        val merged = LinkedHashMap<String, String>()
        source.forEach { (key, value) -> merged[key] = value }
        PRODUCTION_OVERLAY.forEach { (key, value) -> merged[key] = value }
        merged.putIfAbsent("APP_NAME", appName)
        merged["HOST"] = host
        merged["PORT"] = port.toString()
        merged["APP_URL"] = url
        merged["JAVA_OPTS"] = javaOpts
        val ordered = LinkedHashMap<String, String>()
        ENV_KEY_ORDER.forEach { key ->
            merged[key]?.let { ordered[key] = it }
        }
        merged.forEach { (key, value) ->
            ordered.putIfAbsent(key, value)
        }
        return ordered
    }

    fun envCharNeedsQuote(ch: Char): Boolean {
        if (ch.isWhitespace()) {
            return true
        }
        if (ch == '#') {
            return true
        }
        if (ch == '"') {
            return true
        }
        if (ch == '\'') {
            return true
        }
        return ch == '='
    }

    fun quoteEnv(value: String): String {
        if (value.isEmpty()) {
            return ""
        }
        if (!value.any(::envCharNeedsQuote)) {
            return value
        }
        return "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"") + "\""
    }

    fun renderEnvFile(env: Map<String, String>): String {
        val lines = mutableListOf(
            "# Generated by ./grind deploy:systemd — review secrets before install.sh copies this to /etc/kona.",
            "# systemd EnvironmentFile: no `export ` prefix. The process environment overrides a `.env` file.",
        )
        if (env["APP_KEY"].isNullOrBlank()) {
            lines += "# APP_KEY is empty. Run ./grind key:generate on a trusted machine and paste the value."
        }
        env.forEach { (key, value) ->
            lines += "$key=${quoteEnv(value)}"
        }
        return lines.joinToString("\n", postfix = "\n")
    }

    fun renderUnit(
        appName: String,
        prefix: String,
        user: String,
        group: String,
        envFile: String,
        startScript: String,
        javaOpts: String,
    ): String {
        val exec = "$prefix/bin/$startScript --base=$prefix"
        return """
            [Unit]
            Description=Kona $appName
            After=network-online.target
            Wants=network-online.target

            [Service]
            Type=simple
            User=$user
            Group=$group
            WorkingDirectory=$prefix
            EnvironmentFile=$envFile
            Environment=JAVA_OPTS=$javaOpts
            ExecStart=$exec
            Restart=on-failure
            RestartSec=5
            TimeoutStopSec=30
            KillSignal=SIGTERM
            LimitNOFILE=65535
            NoNewPrivileges=true
            PrivateTmp=true

            [Install]
            WantedBy=multi-user.target
            """.trimIndent() + "\n"
    }

    fun renderInstallScript(
        appName: String,
        prefix: String,
        user: String,
        group: String,
        envFile: String,
        unitFile: String,
    ): String {
        val unitName = unitFile.substringAfterLast('/')
        return """
            #!/usr/bin/env bash
            # Generated by ./grind deploy:systemd for $appName
            set -euo pipefail

            PREFIX="${'$'}{PREFIX:-$prefix}"
            ENV_DST="${'$'}{ENV_DST:-$envFile}"
            UNIT_DST="${'$'}{UNIT_DST:-$unitFile}"
            APP_USER="${'$'}{APP_USER:-$user}"
            APP_GROUP="${'$'}{APP_GROUP:-$group}"
            HERE="${'$'}(cd "${'$'}(dirname "${'$'}0")" && pwd)"

            if [[ "${'$'}(id -u)" -ne 0 ]]; then
              echo "Run as root: sudo ${'$'}0" >&2
              exit 1
            fi

            if ! id -u "${'$'}APP_USER" >/dev/null 2>&1; then
              useradd --system --home "${'$'}PREFIX" --shell /usr/sbin/nologin "${'$'}APP_USER"
            fi

            mkdir -p "${'$'}PREFIX" "${'$'}(dirname "${'$'}ENV_DST")" "${'$'}(dirname "${'$'}UNIT_DST")"
            mkdir -p "${'$'}PREFIX/storage/logs" "${'$'}PREFIX/storage/framework" "${'$'}PREFIX/storage/app/public" "${'$'}PREFIX/storage/database"

            if [[ -d "${'$'}HERE/bin" ]]; then
              rm -rf "${'$'}PREFIX/bin"
              cp -a "${'$'}HERE/bin" "${'$'}PREFIX/"
            fi
            if [[ -d "${'$'}HERE/lib" ]]; then
              rm -rf "${'$'}PREFIX/lib"
              cp -a "${'$'}HERE/lib" "${'$'}PREFIX/"
            fi
            if [[ -d "${'$'}HERE/public" ]]; then
              rm -rf "${'$'}PREFIX/public"
              cp -a "${'$'}HERE/public" "${'$'}PREFIX/"
            fi

            install -m 0644 "${'$'}HERE/$appName.service" "${'$'}UNIT_DST"
            if [[ -f "${'$'}ENV_DST" ]]; then
              echo "Keeping existing ${'$'}ENV_DST"
            else
              install -m 0600 "${'$'}HERE/$appName.env" "${'$'}ENV_DST"
            fi

            chown -R "${'$'}APP_USER:${'$'}APP_GROUP" "${'$'}PREFIX"
            chown root:root "${'$'}ENV_DST" 2>/dev/null || true
            chmod 0600 "${'$'}ENV_DST" 2>/dev/null || true

            systemctl daemon-reload
            systemctl enable --now $unitName
            systemctl status --no-pager $unitName
            """.trimIndent() + "\n"
    }

    fun renderReadme(
        appName: String,
        dest: Path,
        prefix: String,
        envFile: String,
        unitFile: String,
    ): String =
        """
        Kona systemd bundle for $appName
        Generated by ./grind deploy:systemd

        This directory
          bin/              start script (from ./gradlew installDist)
          lib/              application JAR + dependencies
          public/           HTTP document root (Vite writes public/build)
          storage/          writable runtime dirs (create-only; logs are not copied)
          $appName.service  systemd unit → $unitFile
          $appName.env      environment file → $envFile
          install.sh        copies the tree, installs the unit, starts the service

        On the server
          1. Review $appName.env (APP_KEY, DB_*, APP_URL). Never commit this file.
          2. sudo ./install.sh
             PREFIX=$prefix ENV_DST=$envFile UNIT_DST=$unitFile
          3. From a checkout that still has ./grind, with the same DB_* values:
             ./grind migrate --force
          4. curl -fsS http://127.0.0.1:4000/api/health

        Default install layout
          $prefix/{bin,lib,public,storage}
          $envFile
          $unitFile

        Do not run ./grind serve in production. The unit starts bin/$appName --base=$prefix

        Scaling (more processes, DB pool, Redis, workers): see the Scaling guide.
        Bundle written to: $dest
        """.trimIndent() + "\n"

    fun resolveInstallDist(root: Path, appName: String): Path? {
        val named = root.resolve("build/install").resolve(appName)
        if (Files.isDirectory(named.resolve("bin"))) {
            return named
        }
        val parent = root.resolve("build/install")
        if (!Files.isDirectory(parent)) {
            return null
        }
        Files.list(parent).use { stream ->
            return stream.filter { Files.isDirectory(it.resolve("bin")) }.findFirst().orElse(null)
        }
    }

    fun unixStartScript(binDir: Path, appName: String): String {
        val preferred = binDir.resolve(appName)
        if (Files.isRegularFile(preferred)) {
            return appName
        }
        if (!Files.isDirectory(binDir)) {
            return appName
        }
        Files.list(binDir).use { stream ->
            return stream
                .map { it.fileName.toString() }
                .filter { !it.endsWith(".bat") && !it.startsWith(".") }
                .sorted()
                .findFirst()
                .orElse(appName)
        }
    }

    fun copyTree(from: Path, to: Path) {
        if (!Files.isDirectory(from)) {
            return
        }
        Files.walk(from).use { stream ->
            stream.forEach { src ->
                if (Files.isSymbolicLink(src)) {
                    return@forEach
                }
                val rel = from.relativize(src)
                if (rel.toString() == "hot") {
                    return@forEach
                }
                val dest = to.resolve(rel.toString())
                if (Files.isDirectory(src)) {
                    Files.createDirectories(dest)
                } else {
                    Files.createDirectories(dest.parent)
                    Files.copy(
                        src,
                        dest,
                        StandardCopyOption.REPLACE_EXISTING,
                        StandardCopyOption.COPY_ATTRIBUTES,
                        LinkOption.NOFOLLOW_LINKS,
                    )
                }
            }
        }
    }

    fun deleteRecursively(path: Path) {
        if (!Files.exists(path)) {
            return
        }
        Files.walk(path).use { stream ->
            stream.sorted(Comparator.reverseOrder()).forEach { Files.deleteIfExists(it) }
        }
    }

    fun ensureStorage(dest: Path) {
        listOf(
            "storage/logs",
            "storage/framework",
            "storage/app/public",
            "storage/database",
        ).forEach { Files.createDirectories(dest.resolve(it)) }
    }

    fun posixView(path: Path): Boolean =
        try {
            Files.getFileStore(path).supportsFileAttributeView("posix")
        } catch (_: Exception) {
            false
        }

    fun markExecutable(path: Path, posix: Boolean = posixView(path)) {
        if (!posix) {
            return
        }
        Files.setPosixFilePermissions(path, PosixFilePermissions.fromString("rwxr-xr-x"))
    }
}
